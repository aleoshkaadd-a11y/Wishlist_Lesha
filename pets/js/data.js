const esc = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
// Ищет псевдоним в начале слова (\b не работает с кириллицей)
export function aliasIndex(text, alias) {
  const a = alias.toLowerCase();
  const tail = a.endsWith(' ') ? '(?=[^a-zа-я0-9]|$)' : '';
  const re = new RegExp('(^|[^a-zа-я0-9])' + esc(a.trim()) + tail, 'i');
  const m = re.exec(text);
  return m ? m.index + m[1].length : -1;
}

export function findLabParam(name) {
  if (!name) return null;
  const n = String(name).toLowerCase().replace(/ё/g, 'е').trim();
  return LAB_PARAMS.find(p => p.key.toLowerCase() === n || p.name.toLowerCase() === n) ||
    LAB_PARAMS.find(p => p.aliases.some(a => aliasIndex(n, a) >= 0));
}
